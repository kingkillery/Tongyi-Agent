def example_8_batch_analysis():
    """Example 8: Analyzing multiple files"""
    print("\n" + "="*60)
    print("Example 8: Batch File Analysis")
    print("="*60)

    try:
        from tongyi_orchestrator import TongyiOrchestrator

        orch = TongyiOrchestrator(root=".")

        # List of files to analyze
        files_to_analyze = [
            "src/cli.py",
            "src/sandbox_exec.py",
            "src/code_search.py"
        ]

        print(f"Analyzing {len(files_to_analyze)} files...\n")

        results = []
        for file_path in files_to_analyze:
            if os.path.exists(file_path):
                answer = orch.run(
                    f"Analyze {file_path} for security issues"
                )
                results.append((file_path, answer))
                print(f"✅ {file_path}")
            else:
                print(f"⚠️  {file_path} not found")

        # Print summary
        print("\n" + "="*60)
        print("Summary:")
        print("="*60)
        for file_path, analysis in results:
            print(f"\n{file_path}:")
            print(analysis[:200] + "..." if len(analysis) > 200 else analysis)

    except Exception as e:
        print(f"Error: {e}")


