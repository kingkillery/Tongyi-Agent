def example_10_concurrent_queries():
    """Example 10: Running multiple queries in sequence"""
    print("\n" + "="*60)
    print("Example 10: Multiple Queries")
    print("="*60)

    try:
        from tongyi_orchestrator import TongyiOrchestrator

        orch = TongyiOrchestrator(root=".")

        queries = [
            "List all Python files in src/",
            "What is the main entry point?",
            "How is configuration managed?",
            "Describe the tool registry"
        ]

        results = []
        for i, query in enumerate(queries, 1):
            print(f"\nQuery {i}/{len(queries)}: {query}")
            answer = orch.run(query)
            results.append(answer)
            print(f"✅ Completed")

        print("\n" + "="*60)
        print("All Results:")
        print("="*60)
        for i, (query, answer) in enumerate(zip(queries, results), 1):
            print(f"\n{i}. {query}")
            print(f"   {answer[:150]}...")

    except Exception as e:
        print(f"Error: {e}")


